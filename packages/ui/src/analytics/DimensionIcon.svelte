<script lang="ts">
	// The icon beside a breakdown row. Flags and browser logos are files; Vite gives them URLs
	// only in the browser build, so they load after mount into a box of fixed size. Device, OS,
	// and fallback icons are Phosphor paths.
	import { onMount } from 'svelte';
	import { flagCodes } from './flags';

	interface Props {
		kind: IconKind;
		value: string;
	}

	let { kind, value }: Props = $props();

	const browsers = new Set(['chrome', 'safari', 'firefox', 'edge', 'samsung', 'opera']);

	// The bundler rewrites these patterns to asset URLs in the browser build only.
	function flagUrl(code: string): string {
		return new URL(`./flags/${code}.svg?no-inline`, import.meta.url).href;
	}
	function browserUrl(name: string): string {
		return new URL(`./browsers/${name}.svg?no-inline`, import.meta.url).href;
	}

	let mounted = $state(false);
	onMount(() => {
		mounted = true;
	});

	const flag = $derived(
		kind === 'country' && flagCodes.has(value.toLowerCase()) ? value.toLowerCase() : null
	);
	const browser = $derived(kind === 'browser' && browsers.has(value) ? value : null);
	const path = $derived.by(() => {
		if (kind === 'referrer') return value === 'unknown' ? phosphor.direct : phosphor.globe;
		if (value === 'unknown') return phosphor.unknown;
		if (kind === 'device') return phosphor[value] ?? phosphor.unknown;
		if (kind === 'os' && (value === 'ios' || value === 'macos')) return phosphor.apple;
		return phosphor[value] ?? phosphor.globe;
	});
</script>

<span class="icon" class:flag={flag !== null} aria-hidden="true">
	{#if flag}
		{#if mounted}<img src={flagUrl(flag)} alt="" width="20" height="15" />{/if}
	{:else if browser}
		{#if mounted}<img src={browserUrl(browser)} alt="" width="18" height="18" />{/if}
	{:else}
		<svg viewBox="0 0 256 256" width="18" height="18" fill="currentColor"><path d={path} /></svg>
	{/if}
</span>

